// results.json (source of truth) and the generated table in RESULTS.md.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ATTACKS_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const RESULTS_JSON = join(ATTACKS_DIR, 'results.json');
export const RESULTS_MD = join(ATTACKS_DIR, 'RESULTS.md');

/** Where the evidence comes from. */
export type Evidence = 'testnet' | 'sandbox' | 'analysis';

export interface AttackResult {
  /** Stable row id, e.g. "03c". Re-running an attack replaces its rows. */
  id: string;
  /** Attack number from the WS-7 brief (1..12, 13+ = extra). */
  attack: number;
  /** Script name (`pnpm --filter @osd/attacks run <script>`). */
  script: string;
  title: string;
  expected: string;
  actual: string;
  /** Did the system behave as expected (attack defeated / handled)? */
  pass: boolean;
  /** Set when the result exposes a weakness to escalate. */
  finding?: string;
  tx?: string | null;
  evidence: Evidence;
  ts: string;
  details?: Record<string, unknown>;
}

export interface ResultsFile {
  version: 1;
  contract: string;
  network: string;
  updated_at: string;
  results: AttackResult[];
}

export function loadResults(path = RESULTS_JSON): ResultsFile {
  if (!existsSync(path)) return { version: 1, contract: '', network: '', updated_at: '', results: [] };
  return JSON.parse(readFileSync(path, 'utf8')) as ResultsFile;
}

/** Insert or replace rows by id, keep them sorted by id. */
export function upsert(file: ResultsFile, rows: AttackResult[], meta: { contract: string; network: string; now?: string }): ResultsFile {
  const byId = new Map(file.results.map((r) => [r.id, r]));
  for (const r of rows) byId.set(r.id, r);
  return {
    version: 1,
    contract: meta.contract,
    network: meta.network,
    updated_at: meta.now ?? new Date().toISOString(),
    results: [...byId.values()].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true })),
  };
}

const EXPLORER = 'https://testnet.nearblocks.io/txns/';

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

export function txCell(r: AttackResult): string {
  if (!r.tx) return r.evidence === 'analysis' ? 'n/a' : '–';
  if (r.evidence !== 'testnet') return `\`${r.tx.slice(0, 10)}…\` (${r.evidence})`;
  return `[\`${r.tx.slice(0, 10)}…\`](${EXPLORER}${r.tx})`;
}

export function renderTable(file: ResultsFile): string {
  const lines = [
    '| # | Attack | Expected | Actual | Result | Tx |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of file.results) {
    const verdict = r.finding ? '**FINDING**' : r.pass ? 'PASS' : '**FAIL**';
    lines.push(`| ${r.id} | ${cell(r.title)} | ${cell(r.expected)} | ${cell(r.actual)} | ${verdict} | ${txCell(r)} |`);
  }
  const pass = file.results.filter((r) => r.pass && !r.finding).length;
  const findings = file.results.filter((r) => r.finding).length;
  const fail = file.results.filter((r) => !r.pass && !r.finding).length;
  lines.push('', `${file.results.length} rows: ${pass} pass, ${findings} finding(s), ${fail} fail. Updated ${file.updated_at}.`);
  return lines.join('\n');
}

const BEGIN = '<!-- results:begin (generated by `pnpm --filter @osd/attacks run render`; edit results.json, not this table) -->';
const END = '<!-- results:end -->';

/** Replace the generated block in RESULTS.md (or append one). */
export function renderInto(md: string, file: ResultsFile): string {
  const block = `${BEGIN}\n${renderTable(file)}\n${END}`;
  const i = md.indexOf('<!-- results:begin');
  const j = md.indexOf(END);
  if (i >= 0 && j > i) return md.slice(0, i) + block + md.slice(j + END.length);
  return `${md.trimEnd()}\n\n${block}\n`;
}

export function save(rows: AttackResult[], meta: { contract: string; network: string }): ResultsFile {
  const file = upsert(loadResults(), rows, meta);
  writeFileSync(RESULTS_JSON, JSON.stringify(file, null, 2) + '\n');
  const md = existsSync(RESULTS_MD) ? readFileSync(RESULTS_MD, 'utf8') : '# WS-7 attack results\n';
  writeFileSync(RESULTS_MD, renderInto(md, file));
  return file;
}

/** One-line console summary per row. */
export function printRows(rows: AttackResult[]): void {
  for (const r of rows) {
    const verdict = r.finding ? 'FINDING' : r.pass ? 'PASS' : 'FAIL';
    console.log(`[${verdict}] ${r.id} ${r.title}\n    expected: ${r.expected}\n    actual:   ${r.actual}${r.tx ? `\n    tx:       ${r.tx}` : ''}`);
  }
}
